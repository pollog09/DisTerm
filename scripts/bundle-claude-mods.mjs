#!/usr/bin/env node
// resources/claude-mods → src/core/token-savers/bundled.generated.ts: the token-saver mods as text,
// so both shells (Electron's vite bundle and the Server Edition's esbuild bundle) carry them with no
// packaging step and no resources path. `npm run mods:bundle` regenerates it;
// src/core/token-savers/bundled.test.ts fails when it is stale. Only what Claude loads is bundled:
// the marketplace manifest and plugins/**, minus tests. shared/ is the source of each plugin's
// hooks/common.ts copy and is checked by the same test, not shipped.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const src = path.join(root, 'resources', 'claude-mods')
const out = path.join(root, 'src', 'core', 'token-savers', 'bundled.generated.ts')

export function collect(dir = src) {
  const files = {}
  const walk = (rel) => {
    for (const e of fs.readdirSync(path.join(dir, rel), { withFileTypes: true })) {
      const r = rel ? `${rel}/${e.name}` : e.name
      if (e.isDirectory()) {
        if (e.name === 'node_modules' || e.name === 'types' && rel.endsWith('.claude-plugin')) continue
        walk(r)
      } else if (!/\.test\.tsx?$/.test(e.name)) {
        files[r] = fs.readFileSync(path.join(dir, r), 'utf8')
      }
    }
  }
  walk('.claude-plugin')
  walk('plugins')
  return Object.fromEntries(Object.keys(files).sort().map((k) => [k, files[k]]))
}

export function render(files) {
  return [
    '// GENERATED by scripts/bundle-claude-mods.mjs from resources/claude-mods. Do not edit.',
    '// Regenerate with `npm run mods:bundle`; bundled.test.ts fails when this is stale.',
    `export const BUNDLED_MODS: Readonly<Record<string, string>> = ${JSON.stringify(files, null, 2)}`,
    ''
  ].join('\n')
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(out, render(collect()))
  console.log(`wrote ${path.relative(root, out)}`)
}
